//! Language carriers: the three settled engines, feature-gated.
//!
//! Every carrier exposes the same contract: source in, JSON value out. The
//! runtime does not interpret what the script means — it received an
//! operation from the control plane and runs its executable part.

use serde_json::Value;

/// What a carrier needs to execute one operation.
pub struct ExecRequest<'a> {
    /// Operation source code (from `ToolCall.code` inline bytes, or fetched
    /// by the caller from a `link` payload before dispatch).
    pub source: &'a str,
    /// Entry point the operation declares (function name); `None` = run the
    /// script top-level and use its result.
    pub entry: Option<&'a str>,
    /// JSON arguments generated by the LLM.
    pub args: &'a Value,
}

pub type ExecResult = anyhow::Result<Value>;

#[cfg(feature = "steel")]
pub mod steel;
#[cfg(feature = "python")]
pub mod python;
#[cfg(feature = "wasmtime")]
pub mod wasmtime;
#[cfg(feature = "nushell")]
pub mod nushell;

/// Dispatch by declared language. Unknown language = error value, never a
/// panic: the control plane declared it, the Probe only validates.
pub fn execute(language: &str, req: ExecRequest) -> anyhow::Result<Value> {
    match language {
        #[cfg(feature = "steel")]
        "steel" => steel::execute(req),
        #[cfg(feature = "python")]
        "python" => python::execute(req),
        #[cfg(feature = "wasmtime")]
        "wasmtime" => wasmtime::execute(req),
        #[cfg(feature = "nushell")]
        "nushell" => nushell::execute(req),
        other => anyhow::bail!("language not carried by this probe build: {other}"),
    }
}

#[cfg(all(test, feature = "nushell"))]
mod nushell_tests {
    use super::*;

    #[test]
    fn nu_entry_with_args() {
        // mirrors the python carrier example: args in, structured result out
        let args = serde_json::json!({ "x": 21 });
        let src = r#"
export def execute [args] {
    { doubled: ($args.x * 2) }
}
"#;
        let out = execute(
            "nushell",
            ExecRequest { source: src, entry: Some("execute"), args: &args },
        )
        .unwrap();
        assert_eq!(out, serde_json::json!({"doubled": 42}));
    }

    #[test]
    fn nu_pipeline_result() {
        let args = serde_json::json!({ "items": [3, 1, 2] });
        let src = r#"
export def execute [args] {
    $args.items | sort
}
"#;
        let out = execute(
            "nushell",
            ExecRequest { source: src, entry: Some("execute"), args: &args },
        )
        .unwrap();
        assert_eq!(out, serde_json::json!([1, 2, 3]));
    }

    #[test]
    fn nu_rejects_main_entry() {
        let args = serde_json::json!(null);
        let err = execute(
            "nushell",
            ExecRequest { source: "export def main [] {}", entry: Some("main"), args: &args },
        )
        .unwrap_err();
        assert!(err.to_string().contains("named function"));
    }
}

#[cfg(all(test, feature = "steel"))]
mod tests {
    use super::*;

    #[test]
    fn steel_entry_with_args() {
        let args = serde_json::json!({ "x": 2 });
        let src = r#"
(define (execute args)
  (string-append "x=" (number->string 2)))
"#;
        let out = execute(
            "steel",
            ExecRequest { source: src, entry: Some("execute"), args: &args },
        )
        .unwrap();
        assert_eq!(out, serde_json::json!("x=2"));
    }

    #[test]
    fn steel_unknown_language_is_error_value() {
        let args = serde_json::json!(null);
        let err = execute(
            "koto",
            ExecRequest { source: "(+ 1 2)", entry: None, args: &args },
        )
        .unwrap_err();
        assert!(err.to_string().contains("koto"));
    }

    #[test]
    fn steel_result_binding() {
        let args = serde_json::json!(null);
        let out = execute(
            "steel",
            ExecRequest {
                source: "(define *result* (* 6 7))",
                entry: None,
                args: &args,
            },
        )
        .unwrap();
        assert_eq!(out, serde_json::json!(42));
    }
}
